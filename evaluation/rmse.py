"""
Real vs Synthetic Control RMSE (Controls, High Dose Only)
==============================================================

Purpose
-------
This script compares *real* test control profiles to *synthetic* control-like
profiles (generated by a VAE / GAN–style model) using RMSE across a
38-biomarker panel.

High-level steps
----------------
1. Load:
   - real_control: per-animal clinical pathology data for test set controls
   - syn_control:  generated predictions for the corresponding test set animals

2. In the synthetic data, **retain only rows with DOSE_LEVEL == "High"**.
   These are interpreted as “control-equivalent profiles conditioned on High dose”.

3. Define the 38-feature panel as **all columns after index 11** in `real_control`
   (0-based indexing: columns[0..10] are metadata, columns[11:] are biomarkers).

4. For each row where real and synthetic data share the same:
      (COMPOUND_NAME, SACRIFICE_PERIOD)
   compute the RMSE between the real and synthetic 38-dimensional biomarker vectors.

5. Save a CSV with columns:
      COMPOUND_NAME, SACRIFICE_PERIOD, rmse

Paths & assumptions
-------------------
- Paths below are **placeholders**; update them to match your environment.
- Assumes both real and synthetic data share:
    * COMPOUND_NAME
    * SACRIFICE_PERIOD
    * DOSE_LEVEL
    * the same biomarker columns (those in FEATURE_38).

- RMSE is computed via sklearn.metrics.mean_squared_error.
"""

import sys
import os
from os.path import join

import pandas as pd
import numpy as np
from sklearn.metrics import mean_squared_error  # <-- use RMSE based on MSE

# -----------------------------
# Load the data (UPDATE PATHS)
# -----------------------------
# Real test controls (per-animal clinical pathology for control dose)
real_control = pd.read_csv(
    "/path/to/repeat_test_control_2d.csv"
)
real_control = pd.concat([real_control.iloc[:, :11], real_control.iloc[:, 1368:]], axis=1)

# Synthetic “control-equivalent” predictions for the same (or similar) animals
syn_control = pd.read_csv(
    "/path/to/results/"
    "predictions_decoded/test/generated_predictions_merged_test.csv"
)

# -----------------------------
# STRICT filter: DOSE_LEVEL must be exactly "High"
# -----------------------------
# In this setup, we treat synthetic rows with DOSE_LEVEL == "High"
# as control-equivalent profiles aligned to High-dose treatment strata.
dose_col = "DOSE_LEVEL"
if dose_col not in syn_control.columns:
    raise KeyError("syn_control is missing 'DOSE_LEVEL' column.")

before_n = len(syn_control)
syn_control = syn_control[syn_control[dose_col] == "High"].copy()
after_n = len(syn_control)
print(
    f"[info] syn_control filtered to DOSE_LEVEL == 'High': "
    f"{after_n}/{before_n} rows retained."
)

# -----------------------------
# 38-feature panel: all columns after index 11 in real_control
# (0-based indexing: columns[0]..columns[10] are meta / IDs / context,
#  columns[11:] are the 38 biomarker measurements)
# -----------------------------
FEATURE_38 = list(real_control.columns[11:])
print("[info] 38-feature panel taken from real_control columns[11:]:")
print(FEATURE_38)


def _prepare_panel_features(real: pd.DataFrame, syn: pd.DataFrame, panel_cols):
    """
    Restrict to panel columns present in BOTH dataframes, coerce to numeric,
    and return the list of feature columns actually used.

    - Columns missing in either dataframe are skipped (with a warning).
    - Non-numeric columns are coerced with `errors='coerce'` and then dropped
      if they remain non-numeric.

    Parameters
    ----------
    real : pd.DataFrame
        Real control dataframe (source of FEATURE_38).
    syn : pd.DataFrame
        Synthetic control-like dataframe.
    panel_cols : list of str
        Candidate biomarker columns (e.g. FEATURE_38).

    Returns
    -------
    list of str
        Usable feature columns that exist and are numeric in both dataframes.

    Raises
    ------
    ValueError
        If no usable panel columns exist in both inputs.
    """
    # Columns that exist in both dataframes
    present_both = [c for c in panel_cols if (c in real.columns and c in syn.columns)]
    missing = [c for c in panel_cols if c not in present_both]
    if missing:
        print(f"[warn] Missing in one/both inputs (skipped): {missing}")
    if not present_both:
        raise ValueError(
            "None of the requested panel columns are present in both dataframes."
        )

    # Coerce to numeric in both real and synthetic data
    for c in present_both:
        real[c] = pd.to_numeric(real[c], errors="coerce")
        syn[c] = pd.to_numeric(syn[c], errors="coerce")

    # Keep only columns that are numeric in both frames
    present_both = [
        c
        for c in present_both
        if pd.api.types.is_numeric_dtype(real[c])
        and pd.api.types.is_numeric_dtype(syn[c])
    ]
    if not present_both:
        raise ValueError(
            "After coercion, none of the panel columns are numeric in both dataframes."
        )

    return present_both


def compute_control_rmse_panel(real: pd.DataFrame, syn: pd.DataFrame, panel_cols, outfile: str):
    """
    Compute Real-vs-Synthetic RMSE using ONLY the given panel columns.

    For each row with matching (COMPOUND_NAME, SACRIFICE_PERIOD):

      • Take the panel feature vector from `real` (e.g., 38 biomarkers).
      • Take the panel feature vector from `syn`.
      • Compute RMSE between these two vectors using mean_squared_error.

    The function:
      - Inner-joins on ['COMPOUND_NAME', 'SACRIFICE_PERIOD'].
      - Cleans NaN / ±inf in features by replacing them with 0.0.
      - Writes a CSV with columns:
            COMPOUND_NAME, SACRIFICE_PERIOD, rmse

    Parameters
    ----------
    real : pd.DataFrame
        Real control dataframe.
    syn : pd.DataFrame
        Synthetic control-like dataframe (already filtered to DOSE_LEVEL == "High").
    panel_cols : list of str
        Biomarker feature columns (e.g. FEATURE_38).
    outfile : str
        Full path to the CSV file to write.

    Returns
    -------
    pd.DataFrame
        DataFrame with columns: ['COMPOUND_NAME', 'SACRIFICE_PERIOD', 'rmse']
    """
    key_cols = ["COMPOUND_NAME", "SACRIFICE_PERIOD"]
    for k in key_cols:
        if k not in real.columns or k not in syn.columns:
            raise KeyError(f"Missing required key column '{k}' in inputs.")

    # Work on copies so we don't mutate the original dataframes
    real = real.copy()
    syn = syn.copy()

    # Restrict to usable numeric feature columns in both real & syn
    feats = _prepare_panel_features(real, syn, panel_cols)
    print(f"[info] Using {len(feats)} feature columns for RMSE calculation.")

    # Align rows by compound & timepoint
    merged = pd.merge(
        real[key_cols + feats],
        syn[key_cols + feats],
        on=key_cols,
        how="inner",
        suffixes=("_real", "_syn"),
    )

    if merged.empty:
        print(f"[warn] Merge produced 0 rows for panel; writing empty file: {outfile}")
        merged.assign(rmse=pd.Series(dtype=float))[key_cols + ["rmse"]].to_csv(
            outfile, index=False
        )
        return merged

    # Clean NaN/inf → 0.0 for the feature columns before RMSE computation
    for c in feats:
        merged[f"{c}_real"] = (
            merged[f"{c}_real"]
            .replace([np.inf, -np.inf], np.nan)
            .fillna(0.0)
        )
        merged[f"{c}_syn"] = (
            merged[f"{c}_syn"]
            .replace([np.inf, -np.inf], np.nan)
            .fillna(0.0)
        )

    real_cols = [f"{c}_real" for c in feats]
    syn_cols = [f"{c}_syn" for c in feats]

    # RMSE per row (treat real as "truth", syn as "prediction")
    rmses = []
    for i in merged.index:
        y_true = merged.loc[i, real_cols].values.astype(float)
        y_pred = merged.loc[i, syn_cols].values.astype(float)
        mse = mean_squared_error(y_true, y_pred)
        rmses.append(float(np.sqrt(mse)))

    merged["rmse"] = rmses

    # Keep only keys + RMSE for downstream analysis
    result = merged[key_cols + ["rmse"]]
    result.to_csv(outfile, index=False)
    print(f"[info] Wrote {len(result)} rows to: {outfile}")
    return result


# -----------------------------
# Output paths (UPDATE BASE PATH)
# -----------------------------
# Base directory for all model outputs / metrics
base_path = "/path/to/results"

# Subfolder where RMSE outputs will be stored
rmse_path = join(base_path, "performance", "rmse", "test")
os.makedirs(rmse_path, exist_ok=True)

# -----------------------------
# Run: single 38-feature RMSE (High dose only)
# -----------------------------
all_out = join(rmse_path, "generated_rmse_all_test.csv")

# This call both computes the RMSE and writes the output CSV
all_df = compute_control_rmse_panel(real_control, syn_control, FEATURE_38, all_out)
